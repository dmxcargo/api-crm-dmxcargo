<?php

use App\Audit\Presentation\AuditController;
use App\Identity\Domain\Role;
use App\Identity\Presentation\AuthController;
use App\Identity\Presentation\UserController;
use App\Sales\Presentation\ActivityController;
use App\Sales\Presentation\ArchiveController;
use App\Sales\Presentation\CustomerController;
use App\Sales\Presentation\DashboardController;
use App\Sales\Presentation\DealController;
